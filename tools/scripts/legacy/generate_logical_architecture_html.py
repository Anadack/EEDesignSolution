# ── Main ─────────────────────────────────────────────────────────────────

def main() -> None:
    base = find_base()
    arch_name, systems = load_systems(base)

    if not systems:
        print("[WARN] No systems found in architecture JSON")
        return

    html = generate_html(arch_name, systems)
    out_dir = base / "exports"
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / "logical_architecture.html"
    out_path.write_text(html, encoding="utf-8")

    total = sum(count_signals(s)["total"] for s in systems)
    ifaces: set[str] = set()
    for s in systems:
        ifaces.update(count_signals(s)["by_interface"].keys())
    print(f"[OK] Generated: {out_path}  ({len(systems)} systems, {total} signals, {len(ifaces)} interface types)")


if __name__ == "__main__":
    main()
