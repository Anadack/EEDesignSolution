def write_reports(outdir: Path, payload: dict[str, Any], cfg: dict[str, Any]) -> None:
    summary = {
        "generated_at": payload["generated_at"],
        "summary": payload["summary"],
        "systems": [
            {"name": s["name"], "source_file": s["source_file"], "stats": s["stats"], "io_counts": s["io"].get("counts", {})}
            for s in payload.get("systems", [])
        ],
        "issues": payload.get("issues", []),
    }
    write_text(outdir / "system_viewer_summary.json", json.dumps(summary, indent=2, ensure_ascii=False))
    codes = [c["code"] for c in cfg.get("io_categories", []) if isinstance(c, dict) and c.get("code")]
    csv_path = outdir / "system_io_matrix.csv"
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["system", "source_file", "total_pins", *codes])
        for s in payload.get("systems", []):
            counts = s.get("io", {}).get("counts", {})
            writer.writerow([s["name"], s["source_file_name"], s["stats"]["io_total"], *[counts.get(code, 0) for code in codes]])


def generate(root: Path, input_path: str | None, outdir: Path, config_path: Path | None, selection_path: Path | None, verbose: bool = False) -> Path:
    cfg = load_config(config_path)
    systems, issues = load_systems(root, input_path, cfg)
    selection = load_selection(selection_path)
    payload = make_payload(root, systems, issues, cfg, selection)
    html = render_html(payload)
    out_html = outdir / str(cfg.get("output_html", "index.html"))
    write_text(out_html, html)
    write_reports(outdir, payload, cfg)
    if verbose:
        print(f"[OK] Systems loaded: {len(systems)}")
        print(f"[OK] Output HTML: {out_html}")
        print(f"[OK] Summary: {outdir / 'system_viewer_summary.json'}")
        print(f"[OK] Matrix CSV: {outdir / 'system_io_matrix.csv'}")
        if issues:
            print(f"[INFO] Issues/warnings: {len(issues)}")
    return out_html


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate an interactive HTML viewer and ECU I/O sizing report from E/E Architect Design v4 system JSON files.")
    parser.add_argument("--root", default=".", help="Project root / workspace. Default: current directory.")
    parser.add_argument("--input", help="System JSON file, folder, or glob. Default: configured input candidates.")
    parser.add_argument("--out", help="Output folder. Default: config output_dir.")
    parser.add_argument("--config", help="Optional viewer config JSON.")
    parser.add_argument("--selection", help="Optional configuration/exclusive-group JSON.")
    parser.add_argument("--verbose", action="store_true", help="Print progress details.")
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    if not root.exists():
        raise SystemExit(f"root not found: {root}")
    config_path = Path(args.config).resolve() if args.config else None
    if config_path is None:
        for cand in (root / "tools" / CONFIG_FILE, Path(__file__).resolve().parent / CONFIG_FILE):
            if cand.exists():
                config_path = cand
                break
    cfg = load_config(config_path)
    outdir = Path(args.out) if args.out else Path(str(cfg.get("output_dir", "generated_doc/system_viewer")))
    if not outdir.is_absolute():
        outdir = root / outdir
    selection_path = Path(args.selection).resolve() if args.selection else None
    if selection_path and not selection_path.exists():
        raise SystemExit(f"selection config not found: {selection_path}")
    html = generate(root, args.input, outdir, config_path, selection_path, args.verbose)
    print(f"Generated: {html}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
