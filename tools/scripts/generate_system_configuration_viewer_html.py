def matches_any(path: Path, patterns: list[str]) -> bool:
    name = path.name
    rel = str(path).replace("\\", "/")
    return any(fnmatch.fnmatch(name, pat) or fnmatch.fnmatch(rel, pat) for pat in patterns)


def discover_files(root: Path, raw_input: str | None, cfg: dict[str, Any]) -> list[Path]:
    candidates: list[Path] = []
    if raw_input:
        raw = Path(raw_input)
        if not raw.is_absolute():
            raw = root / raw
        s = str(raw)
        if any(ch in s for ch in "*?[]"):
            if s.startswith(str(root)):
                candidates = sorted(root.glob(str(raw.relative_to(root))))
            else:
                candidates = sorted(Path().glob(s))
        elif raw.is_file():
            candidates = [raw]
        elif raw.is_dir():
            candidates = sorted(raw.rglob("*.json"))
        else:
            raise FileNotFoundError(f"input path not found: {raw}")
    else:
        for cand in cfg.get("input_candidates", []):
            p = Path(cand)
            if not p.is_absolute():
                p = root / p
            if p.is_file():
                candidates.append(p)
            elif p.is_dir():
                candidates.extend(sorted(p.rglob("*.json")))
    include = list(cfg.get("include_globs", ["*.json"]))
    exclude = list(cfg.get("exclude_globs", []))
    out: list[Path] = []
    seen: set[Path] = set()
    for p in candidates:
        p = p.resolve()
        if p in seen or not p.exists() or not p.is_file():
            continue
        if include and not matches_any(p, include):
            continue
        if exclude and matches_any(p, exclude):
            continue
        out.append(p)
        seen.add(p)
    return sorted(out)


def looks_like_system(data: Any, cfg: dict[str, Any]) -> bool:
    if not isinstance(data, dict):
        return False
    typ = str(data.get("type", data.get("schema", ""))).lower()
    schema = str(data.get("schema_version", data.get("schema", ""))).lower()
    tokens = {str(t).lower() for t in cfg.get("system_type_tokens", [])}
    if typ in tokens or "eec-system" in schema:
        return True
    if data.get("name") and any(k in data for k in ("devices", "components", "sensors", "actuators")):
        return True
    return False


def norm_device_type(dev: dict[str, Any], hint: str = "") -> str:
    raw = best_str(dev, ["device_type", "type", "kind"], "").upper()
    if raw in {"SENSOR", "ACTUATOR"}:
        return raw
    h = hint.lower()
    if h.startswith("sensor"):
        return "SENSOR"
    if h.startswith("actuator"):
        return "ACTUATOR"
    if "drive_topology" in dev or "actuator_template" in dev:
        return "ACTUATOR"
    if "sensor_template" in dev:
        return "SENSOR"
    return raw or "DEVICE"


def collect_devices(raw: dict[str, Any], cfg: dict[str, Any]) -> list[dict[str, Any]]:
    devices: list[dict[str, Any]] = []

    def add(item: Any, hint: str, component: dict[str, Any] | None = None) -> None:
        if not isinstance(item, dict):
            return
        dev = dict(item)
        dev["_viewer_device_type"] = norm_device_type(dev, hint)
        if component:
            dev["_viewer_component_name"] = str(component.get("name", ""))
            dev["_viewer_component"] = {k: v for k, v in component.items() if k not in ("devices", "sensors", "actuators")}
        devices.append(dev)

    for key in cfg.get("top_level_device_keys", []):
        for dev in as_list(raw.get(key)):
            add(dev, key)

    for comp_key in cfg.get("component_keys", []):
        comps = raw.get(comp_key)
        if not isinstance(comps, list):
            continue
        for comp in comps:
            if not isinstance(comp, dict):
                continue
            for key in cfg.get("component_device_keys", []):
                for dev in as_list(comp.get(key)):
                    add(dev, key, comp)
    return devices


def signal_id(sig: dict[str, Any], cfg: dict[str, Any]) -> str:
    return best_str(sig, cfg.get("signal_name_keys", []), "")


def expanded_signal_names(sig: dict[str, Any], cfg: dict[str, Any]) -> list[str]:
    base = signal_id(sig, cfg)
    count = max(1, to_int(sig.get("count", 1), 1))
    if not base:
        return []
    if count == 1:
        return [base]
    return [f"{base}_{i+1:02d}" for i in range(count)]


def build_signal_index(signals: list[dict[str, Any]], cfg: dict[str, Any]) -> dict[str, dict[str, Any]]:
    idx: dict[str, dict[str, Any]] = {}
    for sig in signals:
        if not isinstance(sig, dict):
            continue
        ids: list[str] = []
        for key in cfg.get("signal_name_keys", []):
            v = sig.get(key)
            if isinstance(v, str) and v.strip():
                ids.append(v.strip())
        ids.extend(expanded_signal_names(sig, cfg))
        for item in unique(ids):
            idx[item] = sig
    return idx


def decode_bitmask(value: Any, labels: dict[str, str]) -> list[str]:
    val = to_int(value, 0)
    out: list[str] = []
    for bit_s, name in labels.items():
        bit = to_int(bit_s, 0)
        if bit and (val & bit):
            out.append(str(name))
    return out


def infer_flags_from_text(*parts: Any) -> list[str]:
    txt = " ".join(str(p or "") for p in parts).upper().replace("-", "_")
    flags: list[str] = []
    if any(t in txt for t in ("HIGH_SIDE", "HIGHSIDE", "HS_", "_HS", "DOH", "PDOH", "POH")):
        flags.append("HIGH_SIDE")
    if any(t in txt for t in ("LOW_SIDE", "LOWSIDE", "LS_", "_LS", "DOL", "PDOL")):
        flags.append("LOW_SIDE")
    if any(t in txt for t in ("CURRENT_SENSE", "CURR_SENSE", "CS", "CURRENT SENSE")):
        flags.append("CURRENT_SENSE")
    if "PUSH_PULL" in txt or "PUSH PULL" in txt:
        flags.append("PUSH_PULL")
    return unique(flags)


def signal_ref_from_pin(pin: dict[str, Any], cfg: dict[str, Any]) -> str:
    sig = pin.get("signal")
    if isinstance(sig, dict):
        return signal_id(sig, cfg)
    if isinstance(sig, str):
        return sig
    for key in ("signal_name", "signal_id", "signal_prefix", "net", "net_name"):
        if isinstance(pin.get(key), str) and pin.get(key).strip():
            return pin[key].strip()
    return ""


def get_interface(obj: dict[str, Any], keys: Iterable[str]) -> str:
    return best_str(obj, keys, "").upper()


def get_role(obj: dict[str, Any], keys: Iterable[str] = ("role",)) -> str:
    return best_str(obj, keys, "").upper()


def classify_io(device_type: str, role: str, interface: str, flags: list[str], cfg: dict[str, Any]) -> tuple[str, str]:
    """Return (io_code, ecu_direction) for one device endpoint/pin.

    device role is interpreted from the device point of view:
      sensor OUTPUT => ECU input
      actuator INPUT => ECU output
    """
    dt = (device_type or "").upper()
    role = (role or "").upper()
    iface = (interface or "UNKNOWN").upper()
    flags_u = {f.upper() for f in flags}
    bus = {str(x).upper() for x in cfg.get("bus_interfaces", [])}

    if role == "GROUND" or iface == "GROUND":
        return "GND", "GROUND"
    if role == "SUPPLY" or iface in {"POWER", "SUPPLY", "IGNITION"}:
        return "SUP", "SUPPLY"
    if iface == "SENSOR_SUPPLY":
        return "SENS_SUP", "SUPPLY"
    if role == "INOUT" or iface in bus:
        if iface == "ETHERNET":
            return "ETH", "INOUT"
        return iface, "INOUT"

    # Convert device direction to ECU direction.
    if dt == "SENSOR":
        ecu_dir = "INPUT" if role in {"OUTPUT", "INOUT", ""} else "OUTPUT"
    elif dt == "ACTUATOR":
        ecu_dir = "OUTPUT" if role in {"INPUT", "INOUT", ""} else "INPUT"
    else:
        ecu_dir = "INPUT" if role == "OUTPUT" else "OUTPUT" if role == "INPUT" else "INOUT"

    if ecu_dir == "INPUT":
        if iface in {"ANALOG", "VOLTAGE", "ANALOG_VOLTAGE"}:
            return "AI", ecu_dir
        if iface in {"DIGITAL", "SWITCH_HIGHSIDE", "SWITCH_HIGHSIDE_SMALL"}:
            return "DI", ecu_dir
        if iface == "FREQUENCY":
            return "FI", ecu_dir
        if iface == "SENT":
            return "SENT", ecu_dir
        if iface in {"CURRENT", "ANALOG_CURRENT"}:
            return "CURR", ecu_dir
        if iface == "RESISTANCE":
            return "RES", ecu_dir
        if iface == "TEMPERATURE":
            return "TEMP", ecu_dir
        return "OTHER", ecu_dir

    if ecu_dir == "OUTPUT":
        if iface in {"PWM", "PWM_HIGHSIDE", "PWM_LOWSIDE"}:
            if iface == "PWM_HIGHSIDE" or "HIGH_SIDE" in flags_u:
                return "PWM_HS", ecu_dir
            if iface == "PWM_LOWSIDE" or "LOW_SIDE" in flags_u:
                return "PWM_LS", ecu_dir
            return "PWM", ecu_dir
        if iface in {"DIGITAL", "SWITCH_HIGHSIDE", "SWITCH_HIGHSIDE_SMALL", "LED_LOWSIDE"}:
            if iface in {"SWITCH_HIGHSIDE", "SWITCH_HIGHSIDE_SMALL"} or "HIGH_SIDE" in flags_u:
                return "DO_HS", ecu_dir
            if iface == "LED_LOWSIDE" or "LOW_SIDE" in flags_u:
                return "DO_LS", ecu_dir
            return "DO", ecu_dir
        if iface in {"CURRENT", "ANALOG_CURRENT"}:
            return "CURR", ecu_dir
        if iface in {"ANALOG", "VOLTAGE"}:
            return "AI", ecu_dir
        return "OTHER", ecu_dir

    return "INOUT", "INOUT"


@dataclass
class Demand:
    counts: Counter[str] = field(default_factory=Counter)
    rows: list[dict[str, Any]] = field(default_factory=list)

    def add(self, code: str, row: dict[str, Any]) -> None:
        if not code:
            return
        self.counts[code] += 1
        r = dict(row)
        r["io_code"] = code
        self.rows.append(r)

    def merge(self, other: "Demand") -> None:
        self.counts.update(other.counts)
        self.rows.extend(other.rows)

    def as_json(self) -> dict[str, Any]:
        return {"counts": dict(sorted(self.counts.items())), "rows": self.rows, "total_pins": int(sum(self.counts.values()))}


def normalize_device(dev: dict[str, Any], cfg: dict[str, Any], system_name: str, index: int) -> dict[str, Any]:
    dtype = str(dev.get("_viewer_device_type") or norm_device_type(dev)).upper()
    name = best_str(dev, ["name", "id", "part_number", "supplier_pn"], f"Device_{index+1}")
    did = clean_id(dev.get("id") or f"{system_name}_{name}_{index}")

    connectors = [x for x in dev.get("connectors", []) if isinstance(x, dict)] if isinstance(dev.get("connectors"), list) else []
    signals = [x for x in dev.get("signals", []) if isinstance(x, dict)] if isinstance(dev.get("signals"), list) else []
    sig_index = build_signal_index(signals, cfg)
    pins = [x for x in dev.get("pins", []) if isinstance(x, dict)] if isinstance(dev.get("pins"), list) else []

    elec_labels = {str(k): str(v) for k, v in cfg.get("electrical_flags", {}).items()}
    diag_labels = {str(k): str(v) for k, v in cfg.get("diagnostic_flags", {}).items()}
    demand = Demand()
    norm_pins: list[dict[str, Any]] = []

    def add_endpoint(pin: dict[str, Any], sig: dict[str, Any], ordinal: int, inferred: bool = False, signal_name_override: str = "") -> None:
        signal_name = signal_name_override or signal_ref_from_pin(pin, cfg) or signal_id(sig, cfg) or f"Signal_{ordinal}"
        interface = get_interface(pin, cfg.get("pin_interface_keys", [])) or get_interface(sig, cfg.get("signal_interface_keys", []))
        role = get_role(pin) or get_role(sig, cfg.get("signal_role_keys", []))
        pnum = ""
        for key in cfg.get("pin_number_keys", []):
            if key in pin:
                pnum = str(pin.get(key)); break
        elec_value = pin.get("electrical_requirement", sig.get("electrical_requirement", pin.get("electrical_capability", 0)))
        flags = unique(decode_bitmask(elec_value, elec_labels) + infer_flags_from_text(pin.get("name"), pin.get("group"), pin.get("electrical"), sig.get("prefix"), sig.get("interface")))
        diag_value = pin.get("diagnostics_required", pin.get("diagnostic_flags", sig.get("diagnostics_required", sig.get("diagnostic_flags", 0))))
        diags = decode_bitmask(diag_value, diag_labels)
        io_code, ecu_dir = classify_io(dtype, role, interface, flags, cfg)
        row = {
            "id": clean_id(pin.get("id") or f"{did}_pin_{ordinal}"),
            "number": pnum or str(ordinal),
            "name": best_str(pin, ["name"], signal_name if inferred else f"Pin {ordinal}"),
            "connector": best_str(pin, ["connector", "connector_name"], connectors[0].get("name", "") if connectors else ""),
            "cavity": pin.get("cavity", pin.get("physical_number", pnum or ordinal)),
            "role": role,
            "interface": interface,
            "signal": signal_name,
            "io_code": io_code,
            "ecu_direction": ecu_dir,
            "electrical_flags": flags,
            "diagnostic_flags": diags,
            "inferred_from_signal": inferred,
            "source": pin,
            "signal_source": sig,
        }
        norm_pins.append(row)
        demand.add(io_code, {
            "system": system_name, "device": name, "device_type": dtype,
            "pin": row["name"], "pin_number": row["number"], "connector": row["connector"],
            "signal": signal_name, "interface": interface, "role": role,
            "ecu_direction": ecu_dir, "electrical_flags": flags, "inferred_from_signal": inferred,
        })

    if pins:
        for i, pin in enumerate(pins, 1):
            sig_ref = signal_ref_from_pin(pin, cfg)
            sig = sig_index.get(sig_ref) or (pin.get("signal") if isinstance(pin.get("signal"), dict) else {}) or {}
            add_endpoint(pin, sig, i, False)
    else:
        # Legacy compact device: create one logical endpoint per expanded signal.
        ordinal = 1
        for sig in signals:
            names = expanded_signal_names(sig, cfg) or [signal_id(sig, cfg) or f"Signal_{ordinal}"]
            for name_i in names:
                add_endpoint({}, sig, ordinal, True, name_i)
                ordinal += 1

    return {
        "id": did,
        "name": name,
        "type": dtype,
        "component": str(dev.get("_viewer_component_name", "")),
        "component_properties": dev.get("_viewer_component", {}),
        "properties": {k: v for k, v in dev.items() if not k.startswith("_viewer_") and k not in ("connectors", "signals", "pins")},
        "connectors": connectors,
        "signals": signals,
        "pins": norm_pins,
        "io": demand.as_json(),
    }


def normalize_system(data: dict[str, Any], path: Path, cfg: dict[str, Any]) -> dict[str, Any]:
    name = best_str(data, ["name", "id", "part_number"], path.stem)
    raw_devices = collect_devices(data, cfg)
    devices = [normalize_device(d, cfg, name, i) for i, d in enumerate(raw_devices)]
    demand = Demand()
    for d in devices:
        demand.counts.update(d.get("io", {}).get("counts", {}))
        demand.rows.extend(d.get("io", {}).get("rows", []))
    return {
        "id": clean_id(data.get("id") or name),
        "name": name,
        "source_file": str(path),
        "source_file_name": path.name,
        "properties": {k: v for k, v in data.items() if k not in ("components", "devices", "sensors", "actuators")},
        "devices": devices,
        "io": demand.as_json(),
        "stats": {
            "components": len(data.get("components", [])) if isinstance(data.get("components"), list) else 0,
            "devices": len(devices),
            "sensors": sum(1 for d in devices if d["type"] == "SENSOR"),
            "actuators": sum(1 for d in devices if d["type"] == "ACTUATOR"),
            "connectors": sum(len(d.get("connectors", [])) for d in devices),
            "signals": sum(sum(max(1, to_int(s.get("count", 1), 1)) for s in d.get("signals", []) if isinstance(s, dict)) for d in devices),
            "pins": sum(len(d.get("pins", [])) for d in devices),
            "io_total": int(sum(demand.counts.values())),
        },
    }


def load_systems(root: Path, raw_input: str | None, cfg: dict[str, Any]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    systems: list[dict[str, Any]] = []
    issues: list[dict[str, Any]] = []
    for p in discover_files(root, raw_input, cfg):
        try:
            data = read_json(p)
        except Exception as exc:
            issues.append({"level": "ERROR", "file": str(p), "message": f"JSON read failed: {exc}"})
            continue
        if not looks_like_system(data, cfg):
            issues.append({"level": "INFO", "file": str(p), "message": "Skipped: not a system JSON"})
            continue
        try:
            systems.append(normalize_system(data, p, cfg))
        except Exception as exc:
            issues.append({"level": "ERROR", "file": str(p), "message": f"normalization failed: {exc}"})
    systems.sort(key=lambda s: s["name"].lower())
    # Make display names unique. Some generated workspaces contain both a normalized
    # system and an explicit_originals copy with the same top-level name. The viewer
    # uses system names as UI keys, so duplicate names must be disambiguated while
    # preserving the original JSON name for traceability.
    name_counts = Counter(s["name"] for s in systems)
    if any(v > 1 for v in name_counts.values()):
        for item in systems:
            if name_counts[item["name"]] > 1:
                original = item["name"]
                src = Path(item.get("source_file", item.get("source_file_name", "")))
                parent = src.parent.name if src.parent.name else "source"
                item["original_name"] = original
                item["name"] = f"{original} [{parent}/{item.get('source_file_name', src.name)}]"
                item["id"] = clean_id(item["name"])
    return systems, issues


def load_selection(path: Path | None) -> dict[str, Any]:
    if path and path.exists():
        data = read_json(path)
        if isinstance(data, dict):
            return data
    return {}


def build_selection_model(systems: list[dict[str, Any]], sel: dict[str, Any]) -> dict[str, Any]:
    names = [s["name"] for s in systems]
    name_set = set(names)
    always = [x for x in sel.get("always_active", []) if x in name_set]
    used = set(always)
    groups = []
    for idx, g in enumerate(sel.get("exclusive_groups", [])):
        if not isinstance(g, dict):
            continue
        members = [x for x in g.get("systems", []) if x in name_set]
        if not members:
            continue
        used.update(members)
        groups.append({
            "id": clean_id(g.get("id") or g.get("name") or f"group_{idx+1}"),
            "name": str(g.get("name") or f"Exclusive group {idx+1}"),
            "description": str(g.get("description") or "One system mounted at a time"),
            "systems": members,
            "default": g.get("default") if g.get("default") in members else members[0],
        })
    return {
        "configuration_name": sel.get("configuration_name", "Machine configuration"),
        "always_active": always,
        "exclusive_groups": groups,
        "manual_systems": [n for n in names if n not in used],
    }


def ordered_counts(counts: dict[str, int], cfg: dict[str, Any]) -> list[dict[str, Any]]:
    cat = cfg.get("_category_by_code", {})
    order = cfg.get("_category_order", [])
    keys = [k for k in order if counts.get(k, 0)] + sorted(k for k in counts if k not in order and counts.get(k, 0))
    return [
        {"code": k, "count": int(counts.get(k, 0)), "label": cat.get(k, {}).get("label", k), "description": cat.get(k, {}).get("description", "")}
        for k in keys
    ]


def make_payload(root: Path, systems: list[dict[str, Any]], issues: list[dict[str, Any]], cfg: dict[str, Any], selection_cfg: dict[str, Any]) -> dict[str, Any]:
    aggregate = Counter()
    for s in systems:
        aggregate.update(s.get("io", {}).get("counts", {}))
        s["io"]["ordered"] = ordered_counts(s["io"].get("counts", {}), cfg)
    summary = {
        "systems": len(systems),
        "devices": sum(s["stats"]["devices"] for s in systems),
        "sensors": sum(s["stats"]["sensors"] for s in systems),
        "actuators": sum(s["stats"]["actuators"] for s in systems),
        "pins": sum(s["stats"]["pins"] for s in systems),
        "signals": sum(s["stats"]["signals"] for s in systems),
        "io_aggregate_sum": dict(sorted(aggregate.items())),
    }
    return {
        "schema_version": "eec-system-viewer-data-2.0",
        "title": cfg.get("title", DEFAULT_CONFIG["title"]),
        "generator": SCRIPT_NAME,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z"),
        "root": str(root),
        "io_categories": cfg.get("io_categories", []),
        "systems": systems,
        "selection": build_selection_model(systems, selection_cfg),
        "issues": issues,
        "summary": summary,
    }


