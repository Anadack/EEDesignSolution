/** @brief Agricultural Performance Level (AgPL) assigned to functions or pins.
 *  Ordered low->high so numeric compare works (higher = more capable).
 */
typedef enum EEC_AgplLevel_e {
    EEC_AGPL_A = 0,
    EEC_AGPL_B = 1,
    EEC_AGPL_C = 2,
    EEC_AGPL_D = 3,
    EEC_AGPL_E = 4
} EEC_AgplLevel_t;

