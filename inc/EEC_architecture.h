/** @brief One system grouping components. */
typedef struct EEC_System_s {
    uint32_t id;                                /**< Unique system id. */
    uint8_t variant_id;                         /**< Variant byte (0=base). Only System may have >0. */
    bool obsolete;                              /**< True if this object is obsolete (raises warning on use). */
    char name[64];                              /**< System name. */
    char part_number[64];                       /**< Manufacturer or reference part number. */
    char ref_2x[26];                            /**< Ref-2X identifier string (max 25 chars). */
    float take_rate;                            /**< Take rate in percentage (0.0 to 100.0). */
    bool is_mandatory;                          /**< True if mandatory system, false if optional. */
    bool auto_mapping_enabled;                  /**< False = skip this system during auto-mapping. */
    EEC_SystemLevel_t system_level;              /**< System-level classification such as SL2. */
    EEC_ObjectPriority_t priority;               /**< Relative urgency assigned to the system. */
    EEC_SafetyClass_t safety;                    /**< Safety classification of the system. */
    char location[64];                          /**< Physical zone: Cabin, Chassis, Engine, Implement, etc. */
    struct EEC_Zone_s *zone;                     /**< Assigned zone (NULL = unassigned). Not owned. */
    struct EEC_Architecture_s *owner_architecture; /**< Parent architecture. */
    EEC_Component_t **components;                /**< Dynamic array of component pointers. */
    uint32_t component_count;                   /**< Number of components in this system. */
    uint32_t component_capacity;                /**< Allocated component capacity. */

    /* ── Platform & brand applicability ── */
    char platforms[EEC_SYSTEM_MAX_PLATFORMS][32]; /**< Platform names this system is mounted on. */
    uint32_t platform_count;                    /**< Number of assigned platforms. */
    EEC_Brand_t brands[EEC_SYSTEM_MAX_BRANDS];   /**< Brands this system applies to. */
    uint32_t brand_count;                       /**< Number of assigned brands. */

    /* ── Software components (owned) ──
     * One system owns 1..n SWCs. Each SWC is allocated to one ECU, so a
     * system whose signals are split across several ECUs uses one SWC per ECU. */
    EEC_Swc_t **swcs;                            /**< Dynamic array of owned SWC pointers. */
    uint32_t swc_count;                         /**< Number of SWCs. */
    uint32_t swc_capacity;                      /**< Allocated SWC capacity. */
} EEC_System_t;

/** @brief One physical ECU pin used by the pinout exports. */
typedef struct EEC_EcuPin_s {
    uint32_t id;                  /**< Unique ECU pin id. */
    bool obsolete;                /**< True if this object is obsolete (raises warning on use). */
    uint32_t physical_number;     /**< Physical cavity number inside the connector. */
    char connector_name[16];      /**< Connector reference, for example X1, X2, X1000. */
    char name[64];                /**< Physical pin name shown in pinout HTML. */
    char main_group[32];          /**< Main I/O group. */
    char electrical[160];         /**< Pre-filled electrical description. */
    char sw_config[160];          /**< Pre-filled software configuration keywords. */
    EEC_PinRole_t role;            /**< Physical pin role. */
    EEC_PinInterface_t interface_type; /**< Preferred electrical/communication interface for this ECU pin. */
    uint32_t supported_capability_mask;  /**< Capability mask used for automatic signal matching. */
    uint32_t diagnostic_flags;    /**< Supported diagnostic flags. */
    uint32_t electrical_capability; /**< Bitmask of EEC_ElectricalFlag_t the pin provides. */
    bool is_occupied;             /**< True when a signal is mapped (not used for GROUND pins). */
    uint32_t gnd_connect_count;   /**< Number of device GND signals sharing this pin. */
    EEC_Signal_t *connected_signal;/**< Signal currently mapped on this pin (last for GROUND). */
    char device_pin_name[64];     /**< Device-side pin name copied by the software. */
    char device_pin_desc[128];    /**< Device-side description copied by the software. */
    char **functions;             /**< Dynamic array of alternative functions/groups. */
    uint32_t function_count;      /**< Number of alternative functions. */
    uint32_t function_capacity;   /**< Allocated alternative function capacity. */
    /** Maximum AgPL level this physical pin can safely support. Defaults to E (no restriction). */
    EEC_AgplLevel_t max_agpl;
    /* ── Pre-wiring validation fields ── */
    float current_max;            /**< Maximum continuous current the pin can source/sink (A). 0 = unlimited. */
    /* Supply information provided by this ECU pin (when role == SUPPLY). */
    EEC_SensorSupplyType_t provided_sensor_supply; /**< Named supply output provided by the ECU, or generic/unknown. */
    EEC_SensorGroundType_t provided_sensor_ground; /**< Ground/return provided by this pin. */
    float provided_supply_voltage; /**< Nominal supplied voltage (V), 0 = unspecified. */
    EEC_GroundClass_t ground_class; /**< Ground classification: POWER or LOGIC. */
    EEC_ResetState_t reset_state;   /**< Actual output state at reset/power-on. */
} EEC_EcuPin_t;

/** @brief One ECU object containing physical pins and CAN addresses. */
typedef struct EEC_Ecu_s {
    uint32_t id;                                /**< Unique ECU id. */
    uint8_t variant_id;                         /**< Variant byte (0=base). Only ECU may have >0. */
    bool obsolete;                              /**< True if this object is obsolete (raises warning on use). */
    char name[64];                              /**< ECU name. */
    char part_number[64];                       /**< Manufacturer or reference part number. */
    char variant[16];                           /**< Design variant: SMALL / MEDIUM / LARGE. */
    EEC_ObjectPriority_t priority;               /**< Relative urgency assigned to the ECU. */
    EEC_SafetyClass_t safety;                    /**< Safety classification of the ECU. */
    char location[64];                          /**< Physical zone: Cabin, Chassis, Engine, Implement, etc. */
    uint8_t can_addresses[EEC_ECU_MAX_CAN_ADDRESSES]; /**< Stored CAN node addresses. */
    uint8_t can_address_count;                  /**< Number of valid CAN addresses. */
    struct EEC_Architecture_s *owner_architecture; /**< Parent architecture. */
    EEC_EcuPin_t *pins;                          /**< Dynamic array of physical pins. */
    uint32_t pin_count;                         /**< Number of physical pins. */
    uint32_t pin_capacity;                      /**< Allocated physical pin capacity. */
    EEC_Connector_t *connectors;                 /**< Dynamic array of connectors on this ECU. */
    uint32_t connector_count;                   /**< Number of connectors on this ECU. */
    uint32_t connector_capacity;                /**< Allocated connector capacity. */

    /* ── Hosted SWCs (DERIVED) ──
     * Not authoritative: rebuilt from every SWC whose allocated_ecu == this ECU
     * via EEC_Architecture_RebuildHostedSwcs(). Never populated by hand. */
    EEC_Swc_t **hosted_swcs;                     /**< Derived array of hosted SWC pointers. */
    uint32_t hosted_swc_count;                  /**< Number of hosted SWCs. */
    uint32_t hosted_swc_capacity;               /**< Allocated hosted SWC capacity. */
} EEC_Ecu_t;

/** @brief One node (ECU + port index) on a bus. */
typedef struct EEC_BusNode_s {
    EEC_Ecu_t *ecu;                              /**< Connected ECU. */
    uint8_t   port_index;                       /**< 1-based port (CAN1=1, ETH1=1, etc.). */
} EEC_BusNode_t;

/** @brief One communication bus. */
typedef struct EEC_Bus_s {
    uint32_t id;                                /**< Unique bus id. */
    bool obsolete;                              /**< True if this object is obsolete (raises warning on use). */
    char name[64];                              /**< Bus name (e.g. "Vehicle_CAN"). */
    char part_number[64];                       /**< Manufacturer or reference part number. */
    char ref_2x[26];                            /**< Ref-2X identifier string (max 25 chars). */
    EEC_BusType_t type;                          /**< Bus communication type. */
    uint32_t bitrate;                           /**< Nominal bitrate in bps. */
    EEC_ObjectPriority_t priority;               /**< Relative urgency. */
    EEC_SafetyClass_t safety;                    /**< Safety classification. */
    struct EEC_Architecture_s *owner_architecture; /**< Parent architecture. */

    EEC_BusNode_t *nodes;                        /**< Dynamic array of connected ECU+port nodes. */
    uint32_t node_count;                        /**< Number of connected nodes. */
    uint32_t node_capacity;                     /**< Allocated node capacity. */

    EEC_Signal_t **signals;                      /**< Dynamic array of routed signals. */
    uint32_t signal_count;                      /**< Number of routed signals. */
    uint32_t signal_capacity;                   /**< Allocated signal capacity. */

    /* ── CAN messages on this bus (DERIVED) ──
     * Not authoritative: rebuilt from every message that has a tx port on this
     * bus via EEC_Architecture_RebuildBusMessages(). Used for per-bus DBC export. */
    EEC_Message_t **messages;                    /**< Derived array of message pointers. */
    uint32_t message_count;                     /**< Number of messages on this bus. */
    uint32_t message_capacity;                  /**< Allocated message capacity. */
} EEC_Bus_t;

/** @brief Placement of one logical signal inside a CAN frame.
 *  Wraps an existing architecture signal and adds the on-the-wire layout that
 *  only makes sense inside a message (start bit, length, byte order, scaling). */
typedef struct EEC_MessageSignal_s {
    EEC_Signal_t *signal;                        /**< Reference to the logical signal (not owned). */
    uint16_t start_bit;                          /**< Start bit position in the frame. */
    uint16_t length;                             /**< Signal length in bits. */
    bool     little_endian;                      /**< True = Intel byte order, false = Motorola. */
    float    scale;                              /**< DBC scale factor. */
    float    offset;                             /**< DBC offset. */
    EEC_Ecu_t *receivers[EEC_MSG_MAX_RX];        /**< Receiving ECU nodes (Rx). */
    uint8_t   receiver_count;                    /**< Number of receivers. */
} EEC_MessageSignal_t;

/** @brief One transmit binding of a message: an ECU CAN port on a given bus.
 *  A message may have several tx bindings, so the same frame can be broadcast
 *  on several of the sending ECU's ports and therefore on several buses.
 *  (bus, ecu, port_index) are stable identifiers rather than a pointer into a
 *  reallocatable bus node array. */
typedef struct EEC_MessageTx_s {
    EEC_Bus_t *bus;                              /**< Bus this port transmits on. */
    EEC_Ecu_t *ecu;                              /**< ECU owning the CAN port (== owner_swc->allocated_ecu). */
    uint8_t    port_index;                       /**< CAN channel index (1-based). */
    uint32_t   cycle_time_ms;                    /**< Periodicity on this bus (0 = event-driven). */
} EEC_MessageTx_t;

/** @brief One CAN message (frame) produced by a SWC.
 *  Owned by the SWC (hence by the system): moving the SWC to another ECU moves
 *  its messages with it. Transport bindings (tx_ports) are recomputed at mapping. */
typedef struct EEC_Message_s {
    uint32_t id;                                 /**< Unique message id. */
    bool     obsolete;                           /**< True if obsolete (warns on use). */
    char     name[64];                           /**< Message name (DBC BO_). */
    uint32_t frame_id;                           /**< CAN identifier (11 or 29 bit). */
    bool     is_extended;                        /**< True = 29-bit (J1939), false = 11-bit. */
    uint32_t pgn;                                /**< J1939 PGN, auto-derived from frame_id by
                                                        EEC_Swc_CreateMessage() for extended (29-bit)
                                                        messages (see EEC_J1939_PgnFromFrameId());
                                                        0 for standard 11-bit messages. */
    uint8_t  dlc;                                /**< Data length code in bytes. */
    EEC_ObjectPriority_t priority;               /**< Relative urgency. */
    EEC_SafetyClass_t    safety;                 /**< Safety classification. */
    struct EEC_Swc_s *owner_swc;                 /**< Owning SWC (back-reference). */

    EEC_MessageTx_t *tx_ports;                   /**< Dynamic array of tx bindings (1..n). */
    uint32_t tx_count;                          /**< Number of tx bindings. */
    uint32_t tx_capacity;                       /**< Allocated tx capacity. */

    EEC_MessageSignal_t *entries;                /**< Dynamic array of signal placements. */
    uint32_t entry_count;                       /**< Number of signal placements. */
    uint32_t entry_capacity;                    /**< Allocated entry capacity. */
} EEC_Message_t;

/** @brief Software component: the logical/software behaviour of a system,
 *  allocated to exactly one ECU. Owns the CAN messages it produces. */
typedef struct EEC_Swc_s {
    uint32_t id;                                 /**< Unique runtime SWC id. */
    bool     obsolete;                           /**< True if obsolete (warns on use). */
    char     name[64];                           /**< SWC name. */
    char     ref_2x[26];                         /**< Stable SWC Ref-2X identifier (own; not the system's). */
    struct EEC_System_s *owner_system;           /**< Owning system. */
    struct EEC_Architecture_s *owner_architecture; /**< Owning architecture. */
    EEC_Ecu_t *allocated_ecu;                    /**< ECU this SWC runs on (NULL = unallocated). */

    EEC_Message_t **messages;                    /**< Dynamic array of owned messages (0..n). */
    uint32_t message_count;                     /**< Number of messages. */
    uint32_t message_capacity;                  /**< Allocated message capacity. */

    /* Software variables produced internally by this SWC. These reference
     * signals registered in arch->signals (not owned here); any of them may be
     * packed into a CAN message even without a physical device pin. */
    EEC_Signal_t **variables;                    /**< Dynamic array of produced signal pointers. */
    uint32_t variable_count;                    /**< Number of software variables. */
    uint32_t variable_capacity;                 /**< Allocated variable capacity. */
} EEC_Swc_t;

/** @brief Architecture distribution mode. */
typedef enum EEC_ArchMode_e {
    EEC_ARCH_MODE_CENTRAL = 0, /**< Systems routed across all ECUs (default). */
    EEC_ARCH_MODE_ZONAL        /**< Systems routed only to their assigned zone's ECUs. */
} EEC_ArchMode_t;

/** @brief A physical/functional zone grouping a subset of ECUs.
 *  Systems assigned to a zone are, in ZONAL mode, mapped only onto that zone's ECUs. */
typedef struct EEC_Zone_s {
    uint32_t id;                                 /**< Unique zone id. */
    char name[64];                               /**< Zone name (e.g. "Cabin", "Powertrain"). */
    struct EEC_Architecture_s *owner_architecture; /**< Parent architecture. */
    EEC_Ecu_t **ecus;                            /**< ECUs in this zone (referenced, not owned). */
    uint32_t ecu_count;                          /**< Number of ECUs in the zone. */
    uint32_t ecu_capacity;                       /**< Allocated ECU pointer capacity. */
} EEC_Zone_t;

/** @brief Top-level architecture container. */
typedef struct EEC_Architecture_s {
    uint32_t id;               /**< Architecture id. */
    bool obsolete;             /**< True if this object is obsolete (raises warning on use). */
    char name[128];            /**< Architecture name used in exports. */
    char part_number[64];      /**< Manufacturer or reference part number. */
    EEC_ObjectPriority_t priority; /**< Relative urgency assigned to the architecture. */
    EEC_SafetyClass_t safety;   /**< Safety classification of the architecture. */
    EEC_IdContext_t ids;        /**< Auto-ID generator state. */

    EEC_Signal_t **signals;     /**< Dynamic array of all architecture signals. */
    uint32_t signal_count;     /**< Number of registered signals. */
    uint32_t signal_capacity;  /**< Allocated signal pointer capacity. */

    EEC_System_t **systems;     /**< Dynamic array of all systems. */
    uint32_t system_count;     /**< Number of registered systems. */
    uint32_t system_capacity;  /**< Allocated system pointer capacity. */

    EEC_Ecu_t **ecus;           /**< Dynamic array of all ECUs. */
    uint32_t ecu_count;        /**< Number of registered ECUs. */
    uint32_t ecu_capacity;     /**< Allocated ECU pointer capacity. */

    EEC_Bus_t **buses;          /**< Dynamic array of all buses. */
    uint32_t bus_count;        /**< Number of registered buses. */
    uint32_t bus_capacity;     /**< Allocated bus pointer capacity. */

    EEC_ArchMode_t mode;        /**< Distribution mode (CENTRAL default, or ZONAL). */
    EEC_Zone_t **zones;         /**< Dynamic array of zones. */
    uint32_t zone_count;       /**< Number of registered zones. */
    uint32_t zone_capacity;    /**< Allocated zone pointer capacity. */
} EEC_Architecture_t;

/** @brief Allocate and initialize a new top-level architecture container.
 *  @param name Human-readable architecture name, or NULL to use a default name.
 *  @return Newly allocated architecture instance, or NULL on allocation failure.
 */
EEC_Architecture_t *EEC_Architecture_Create(const char *name);

/** @brief Release an architecture and every object registered below it.
 *  @param arch Architecture to destroy. NULL is accepted.
 */
void EEC_Architecture_Destroy(EEC_Architecture_t *arch);

/** @brief Replace the exported name of an existing architecture.
 *  @param arch Architecture to update.
 *  @param name New display name to copy.
 */
void EEC_Architecture_SetName(EEC_Architecture_t *arch, const char *name);

/** @brief Create and register one logical signal in the architecture.
 *  @param arch Owning architecture.
 *  @param name Signal name used in reports and exports.
 *  @param type Payload representation carried by the signal.
 *  @param interface_type Electrical or communication interface used for routing.
 *  @param unit Engineering unit associated with the signal value.
 *  @param min_value Minimum engineering value.
 *  @param max_value Maximum engineering value.
 *  @param resolution Resolution or least significant bit in engineering units.
 *  @param scaling Scaling factor applied by downstream tooling.
 *  @return Newly created signal, or NULL on invalid input or allocation failure.
 */
EEC_Signal_t *EEC_Architecture_CreateSignalEx(
    EEC_Architecture_t *arch,
    const char *name,
    EEC_SignalType_t type,
    EEC_SignalInterface_t interface_type,
    EEC_SignalUnit_t unit,
    float min_value,
    float max_value,
    float resolution,
    float scaling
);

